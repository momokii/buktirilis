def _iso(value: datetime | None) -> str | None:
    return value.isoformat().replace("+00:00", "Z") if value else None


def build_snapshot(
    db: Session,
    *,
    project: Project,
    run: Run,
    scope: str = "full",
    scope_detail: dict[str, Any] | None = None,
) -> dict[str, Any]:
    build = db.get(Build, run.build_id)
    if build is None:
        raise HTTPException(status_code=409, detail="Run has no build record")
    baseline = db.get(Run, run.baseline_run_id) if run.baseline_run_id else None
    rows = build_run_view(db, run)
    comparison: list[dict[str, Any]] = []
    buckets: dict[str, int] = {}
    if baseline is not None:
        comparison = comparison_findings(db, baseline, run)
        buckets = bucket_counts(comparison)
    profile = get_profile(run.profile_code, run.profile_version)
    checks = list(db.execute(select(RunCheck).where(RunCheck.run_id == run.id)).scalars())
    surfaces = list(db.execute(select(Surface).where(Surface.run_id == run.id)).scalars())
    filter_payload = scope_detail or {}
    findings_payload = []
    for item in rows:
        if not _include(item.finding, filter_payload):
            continue
        findings_payload.append(_finding_snapshot(db, run=run, item=item, baseline=baseline))
    retests = []
    for attempt in db.execute(
        select(RetestAttempt)
        .where(RetestAttempt.run_id == run.id)
        .order_by(RetestAttempt.requested_at)
    ).scalars():
        retests.append(
            {
                k: v
                for k, v in attempt_row(db, attempt, include_evidence=False).items()
                if k
                in {
                    "id",
                    "kind",
                    "state",
                    "outcome",
                    "reason_code",
                    "reason",
                    "finding_id",
                    "finding_public_id",
                    "build_id",
                    "build_label",
                    "recipe_revision",
                    "requested_by",
                    "requested_at",
                    "build_identity",
                    "positive_control",
                    "assertion_result",
                    "reviews",
                }
            }
        )
    latest_panel = []
    if run.completed_at is not None:
        for item in rows:
            observation = latest_observation(db, item.finding.id, run.build_id)
            if observation is None or observation.observed_at <= run.completed_at:
                continue
            from app.domain import OBSERVATION_TO_VERIFICATION, ObservationOutcome

            latest_panel.append(
                {
                    "finding_public_id": item.finding.public_id,
                    "outcome": OBSERVATION_TO_VERIFICATION[
                        ObservationOutcome(observation.outcome)
                    ].value,
                    "observation_outcome": observation.outcome,
                    "source": observation.source,
                    "observed_at": _iso(observation.observed_at),
                    "verification_kind": "latest_verification",
                }
            )
    snapshot_scope = run.scope_snapshot or {}
    payload = {
        "schema_version": SCHEMA_VERSION,
        "generated_at": datetime.now(UTC).isoformat().replace("+00:00", "Z"),
        "snapshot_at": _iso(run.completed_at),
        "scope": scope,
        "scope_detail": filter_payload,
        "project": {
            "id": str(project.id),
            "slug": project.slug,
            "name": project.name,
        },
        "builds": [
            {
                "id": str(build.id),
                "label": build.label,
                "target_url": build.target_url,
                "environment": snapshot_scope.get("environment_label", ""),
                "commit_sha": build.commit_sha,
                "build_identity": build.expected_identity,
                "build_identity_source": snapshot_scope.get("build_identity_source", ""),
            }
        ],
        "run": {
            "id": str(run.id),
            "kind": run.kind,
            "mode": run.mode,
            "depth": run.depth,
            "status": run.status,
            "profile": {"code": run.profile_code, "version": run.profile_version},
            "engine": run.engine,
            "engine_version": run.engine_version,
            "requested_by": run.requested_by_label,
            "created_at": _iso(run.created_at),
            "started_at": _iso(run.started_at),
            "completed_at": _iso(run.completed_at),
            "budget": run.budget,
            "coverage_complete": run.coverage_complete,
            "ingest_state": run.ingest_state,
            "summary": run.summary,
            "failure_reason": run.failure_reason,
            "baseline_run_id": str(baseline.id) if baseline else None,
        },
        "counts": {
            "severity": severity_counts(rows),
            "records": len(rows),
            "comparison": buckets,
            "coverage": coverage_counts(db, run),
        },
        "findings": findings_payload,
        "coverage": {
            "summary": coverage_counts(db, run),
            "rows": [_check_payload(check) for check in checks],
            "surfaces": [
                {
                    "route": surface.route,
                    "methods": surface.methods,
                    "source": surface.source,
                    "tested": surface.tested,
                }
                for surface in surfaces
            ],
            "planned_checks": (run.scope_snapshot or {}).get("planned_checks", []),
        },
        "retests": retests,
        "latest_verification": latest_panel,
        "methodology": {
            "profile": profile_as_json(profile),
            "depth_limits": (run.scope_snapshot or {}).get("limits", {}),
            "scope": {
                "base_url": snapshot_scope.get("base_url"),
                "allowed_origins": snapshot_scope.get("allowed_origins", []),
                "path_prefixes": snapshot_scope.get("path_prefixes", []),
                "accounts": snapshot_scope.get("accounts", []),
                "unauthenticated": snapshot_scope.get("unauthenticated", False),
                "approval": snapshot_scope.get("approval", {}),
            },
            "release_plan": snapshot_scope.get("release_plan"),
            "limitations": list(run.limitations or []),
        },
        "limitations": list(run.limitations or []),
        "notices": [
            "This report covers only the recorded scope and checks. It is not a certification.",
            "Engine spend is an estimate and can overshoot the configured budget.",
            "Demo records are deterministic fixtures and are excluded from live comparisons.",
        ],
    }
    return redact_payload(payload)


def _check_payload(check: RunCheck) -> dict[str, Any]:
    return {
        "id": str(check.id),
        "check_key": check.check_key,
        "stage": check.stage,
        "scenario_code": check.scenario_code,
        "scenario_title": check.scenario_title,
        "surface": check.surface,
        "method": check.method,
        "actor": check.actor_label,
        "approach": check.approach,
        "source": check.coverage_source,
        "result": check.result,
        "result_detail": check.result_detail,
        "owasp_refs": check.owasp_refs,
        "finding_id": str(check.finding_id) if check.finding_id else None,
    }


def _include(finding: Finding, filters: dict[str, Any]) -> bool:
    if not filters:
        return True
    severity = filters.get("severity")
    return not (isinstance(severity, list) and severity and finding.severity not in severity)


def _finding_snapshot(db: Session, *, run: Run, item, baseline: Run | None) -> dict[str, Any]:
    finding = item.finding
    build = db.get(Build, run.build_id)
    evidence = list(
        db.execute(
            select(Evidence).where(Evidence.finding_id == finding.id).order_by(Evidence.created_at)
        ).scalars()
    )
    attempts = list(
        db.execute(
            select(RetestAttempt)
            .where(
                RetestAttempt.finding_id == finding.id,
                RetestAttempt.build_id == run.build_id,
            )
            .order_by(RetestAttempt.requested_at)
        ).scalars()
    )
    history = list(
        db.execute(
            select(Observation)
            .where(Observation.finding_id == finding.id)
            .order_by(Observation.observed_at)
        ).scalars()
    )
    observations = []
    for observation in history:
        observation_build = db.get(Build, observation.build_id)
        observations.append(
            {
                "outcome": observation.outcome,
                "source": observation.source,
                "observed_at": _iso(observation.observed_at),
                "build_label": observation_build.label if observation_build else "",
                "stale": bool((observation.detail or {}).get("stale")),
            }
        )
    base_state = None
    if baseline is not None:
        from app.services.findings import state_for_build

        base_state = state_for_build(db, finding.id, baseline.build_id, as_of=baseline.completed_at)
    return {
        "id": str(finding.id),
        "public_id": finding.public_id,
        "title": finding.title,
        "severity": finding.severity,
        "issue_class": finding.issue_class,
        "affected_scope": finding.scope_summary,
        "actors": finding.actors_summary,
        "impact": finding.impact,
        "expected_behavior": finding.expected_behavior,
        "observed_behavior": finding.observed_behavior,
        "remediation": finding.remediation,
        "prerequisites": finding.prerequisites,
        "reproduction_steps": finding.reproduction_steps,
        "root_cause_hypothesis": finding.root_cause_hypothesis,
        "evidence_status": finding.evidence_status,
        "retest_method": eligibility(finding),
        "disposition": finding.disposition,
        "disposition_reason": finding.disposition_reason,
        "verification": {
            "outcome": item.state.outcome.value,
            "source": item.state.source,
            "observed_at": _iso(item.state.observed_at),
            "reason": item.state.reason_text,
            "stale": item.state.stale,
        },
        "run_outcome": _run_outcome(item),
        "baseline_outcome": base_state.outcome.value if base_state else None,
        "build": {"id": str(build.id) if build else "", "label": build.label if build else ""},
        "evidence": [evidence_row(row) for row in evidence],
        "attempts": [
            {
                "id": str(attempt.id),
                "kind": attempt.kind,
                "state": attempt.state,
                "outcome": attempt.outcome,
                "reason": attempt.reason_text,
                "requested_by": attempt.requested_by_label,
                "requested_at": _iso(attempt.requested_at),
                "build_identity": {
                    "expected": attempt.build_identity_expected,
                    "observed": attempt.build_identity_observed,
                },
                "positive_control": attempt.positive_control,
            }
            for attempt in attempts
        ],
        "observation_history": observations,
        "links": {
            "finding": f"/projects/{run.project_id}/findings/{finding.id}",
            "run": f"/projects/{run.project_id}/runs/{run.id}",
        },
    }


def _run_outcome(item) -> str | None:
    for observation in sorted(item.observations, key=lambda o: o.observed_at, reverse=True):
        if observation.outcome in {"observed", "not_observed"}:
            return observation.outcome
    return item.latest_attempt.outcome if item.latest_attempt else None


def render_json(snapshot: dict[str, Any]) -> bytes:
    return json.dumps(snapshot, indent=2, sort_keys=False, ensure_ascii=False).encode("utf-8")


