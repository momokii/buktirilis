def _evidence_excerpt(evidence: dict[str, Any]) -> str:
    payload = redact_payload(evidence.get("payload") or {})
    if evidence.get("kind") == "engine_report":
        text = str(payload.get("evidence") or payload.get("description") or "")
        return truncate(text, 1200)
    request = payload.get("request") or {}
    response = payload.get("response") or {}
    lines = [
        f"{request.get('method', '')} {request.get('url', '')}".strip(),
        f"→ {response.get('status')} {response.get('headers', {}).get('content-type', '')}".strip(),
    ]
    body = str(response.get("body") or "")
    if body:
        lines.append(truncate(body, 900))
    for line in evidence.get("highlight") or []:
        lines.append(f"highlight: {line}")
    return "\n".join(lines)


