def create_export(
    db: Session,
    *,
    project: Project,
    run: Run,
    fmt: str,
    actor: User,
    scope: str = "full",
    scope_detail: dict[str, Any] | None = None,
) -> list[ExportSnapshot]:
    if fmt not in EXPORT_FORMATS:
        raise HTTPException(
            status_code=422, detail="Supported export formats are PDF, CSV, and JSON"
        )
    snapshot = build_snapshot(db, project=project, run=run, scope=scope, scope_detail=scope_detail)
    snapshot_bytes = render_json(snapshot)
    created: list[ExportSnapshot] = []
    if fmt == "json":
        artifact = save_bytes(
            db,
            project=project,
            content=snapshot_bytes,
            filename=f"buktirilis-{run.id}-report.json",
            content_type="application/json",
            created_by=actor.id,
        )
        created.append(
            _persist_export(
                db,
                project=project,
                run=run,
                fmt="json",
                scope=scope,
                scope_detail=scope_detail or {},
                payload=snapshot,
                artifact=artifact,
                actor=actor,
            )
        )
    elif fmt == "csv":
        findings_bytes = render_csv_findings(snapshot)
        coverage_bytes = render_csv_coverage(snapshot)
        findings_artifact = save_bytes(
            db,
            project=project,
            content=findings_bytes,
            filename=f"buktirilis-{run.id}-findings.csv",
            content_type="text/csv",
            created_by=actor.id,
        )
        coverage_artifact = save_bytes(
            db,
            project=project,
            content=coverage_bytes,
            filename=f"buktirilis-{run.id}-coverage.csv",
            content_type="text/csv",
            created_by=actor.id,
        )
        created.append(
            _persist_export(
                db,
                project=project,
                run=run,
                fmt="csv_findings",
                scope=scope,
                scope_detail=scope_detail or {},
                payload=snapshot,
                artifact=findings_artifact,
                actor=actor,
            )
        )
        created.append(
            _persist_export(
                db,
                project=project,
                run=run,
                fmt="csv_coverage",
                scope=scope,
                scope_detail=scope_detail or {},
                payload=snapshot,
                artifact=coverage_artifact,
                actor=actor,
            )
        )
    else:
        pdf_bytes = render_pdf(snapshot)
        artifact = save_bytes(
            db,
            project=project,
            content=pdf_bytes,
            filename=f"buktirilis-{run.id}-report.pdf",
            content_type="application/pdf",
            created_by=actor.id,
        )
        created.append(
            _persist_export(
                db,
                project=project,
                run=run,
                fmt="pdf",
                scope=scope,
                scope_detail=scope_detail or {},
                payload=snapshot,
                artifact=artifact,
                actor=actor,
            )
        )
    db.flush()
    return created


def _persist_export(
    db: Session,
    *,
    project: Project,
    run: Run,
    fmt: str,
    scope: str,
    scope_detail: dict[str, Any],
    payload: dict[str, Any],
    artifact: Artifact,
    actor: User,
) -> ExportSnapshot:
    snapshot = ExportSnapshot(
        project_id=project.id,
        run_id=run.id,
        format=fmt,
        scope=scope,
        scope_detail=scope_detail,
        schema_version=SCHEMA_VERSION,
        payload=payload,
        artifact_id=artifact.id,
        sha256=artifact.sha256,
        size_bytes=artifact.size_bytes,
        created_by=actor.id,
    )
    db.add(snapshot)
    db.flush()
    return snapshot


def export_row(snapshot: ExportSnapshot) -> dict[str, Any]:
    return {
        "id": str(snapshot.id),
        "format": snapshot.format,
        "scope": snapshot.scope,
        "scope_detail": snapshot.scope_detail,
        "schema_version": snapshot.schema_version,
        "sha256": snapshot.sha256,
        "size_bytes": snapshot.size_bytes,
        "created_at": _iso(snapshot.created_at),
        "download_url": f"/api/projects/{snapshot.project_id}/exports/{snapshot.id}/download",
    }


def latest_exports(db: Session, run: Run) -> list[ExportSnapshot]:
    return list(
        db.execute(
            select(ExportSnapshot)
            .where(ExportSnapshot.run_id == run.id)
            .order_by(ExportSnapshot.created_at.desc())
        ).scalars()
    )


