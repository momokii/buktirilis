#!/usr/bin/env bash
# One-command demo deployment for a Linux host with Docker Compose v2.
#
#   ./scripts/deploy.sh [bind-interface] [port]
#
# Defaults to 127.0.0.1:8080. For a Tailscale-only deployment pass the Tailscale IPv4:
#   ./scripts/deploy.sh 100.x.y.z 8088
#
# This starts the DEMO stack (staging mode, synthetic lab, live execution disabled).
# It never enables live scanning or exposes the API/database/lab publicly.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BIND="${1:-127.0.0.1}"
PORT="${2:-8080}"
cd "$ROOT"

command -v docker >/dev/null || { echo "docker is required" >&2; exit 1; }
docker compose version >/dev/null || { echo "docker compose v2 is required" >&2; exit 1; }

if [ ! -f .env ]; then
  command -v python3 >/dev/null || { echo "python3 is required to generate local secrets" >&2; exit 1; }
  SECRET="$(python3 -c 'import secrets; print(secrets.token_urlsafe(48))')"
  DBPASS="$(python3 -c 'import secrets; print(secrets.token_urlsafe(32))')"
  umask 077
  cat > .env <<ENV
# Generated by scripts/deploy.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
APP_ENV=staging
PUBLIC_ORIGIN=http://${BIND}:${PORT}
DATABASE_URL=postgresql+psycopg://buktirilis:${DBPASS}@127.0.0.1:55432/buktirilis
POSTGRES_USER=buktirilis
POSTGRES_PASSWORD=${DBPASS}
POSTGRES_DB=buktirilis
BUKTIRILIS_SECRET_KEY=${SECRET}
COOKIE_SECURE=false
ARTIFACT_ROOT=/srv/var/artifacts
STRIX_RUNS_ROOT=/srv/var/strix_runs
LAB_BASE_URL=http://lab:8099
ALLOW_LOOPBACK_LAB_TARGETS=false
DEMO_SEED_ENABLED=true
LIVE_EXECUTION_ENABLED=false
STRIX_MODEL=
EVIDENCE_RETENTION_DAYS=0
WEB_BIND=${BIND}
WEB_PORT=${PORT}
ENV
  chmod 600 .env
  echo "wrote .env (mode 600) with generated local secrets"
else
  echo "using existing .env"
fi

echo "building and starting the demo stack on ${BIND}:${PORT}"
docker compose --profile demo up -d --build
docker compose --profile demo exec -T api python -m app.cli seed-demo \
  --credentials-file /srv/var/demo-credentials.txt
mkdir -p var
docker compose cp api:/srv/var/demo-credentials.txt var/demo-credentials.txt
chmod 600 var/demo-credentials.txt

echo "waiting for health"
for _ in $(seq 1 30); do
  if curl -fsS "http://${BIND}:${PORT}/api/health" >/dev/null 2>&1; then break; fi
  sleep 2
done
curl -fsS "http://${BIND}:${PORT}/api/health" >/dev/null
echo "demo ready: http://${BIND}:${PORT}"
echo "credentials: ${ROOT}/var/demo-credentials.txt (mode 600)"
echo "next: sign in, rotate the admin password, and review docs/deploying-elsewhere.md"
